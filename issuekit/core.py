@dataclass(frozen=True)
class Issue:
    id: int | None
    ref: str
    title: str
    issue_status: str
    created: str
    completed: str
    priority: str
    assignee: str
    stage: str
    implementer: str
    author: str
    body: str
    metadata: dict[str, Any]
    worker: str = ""
    target_worker: str = ""
    depends_on: tuple[str, ...] = ()
    dependencies: tuple[dict[str, object], ...] = ()
    dependency_state: str = ""
    warning: str = ""


@dataclass(frozen=True)
class TargetAddress:
    repo: str
    worker: str = ""
    machine: str = ""

    @property
    def directed_worker(self) -> str:
        """Return the worker token to send as a directed target."""
        if self.worker and self.machine:
            return f"{self.worker}@{self.machine}"
        return self.worker


def issue_dict(issue: "Issue", *, include_body: bool = False) -> dict[str, object]:
    """Serialize an issue for JSON output.

    Shared by the MCP server and the CLI so both paths emit identical payloads.
    """
    data: dict[str, object] = {
        "id": issue.id,
        "title": issue.title,
        "status": issue.issue_status,
        "assignee": issue.assignee,
        "stage": issue.stage,
        "implementer": issue.implementer,
        "author": issue.author,
        "ref": issue.ref,
    }
    if include_body:
        data["body"] = issue.body
    if issue.worker:
        data["worker"] = issue.worker
    if issue.target_worker:
        data["target_worker"] = issue.target_worker
    if issue.depends_on:
        data["depends_on"] = list(issue.depends_on)
    if issue.dependency_state:
        data["dependency_state"] = issue.dependency_state
    if issue.dependencies:
        data["dependencies"] = [dict(item) for item in issue.dependencies]
    if issue.warning:
        data["warning"] = issue.warning
    for key in ("author_session", "implementer_session", "reviewer_session"):
        value = issue.metadata.get(key)
        if value:
            data[key] = value
    return data


def _drop_none(values: Mapping[str, Any]) -> dict[str, Any]:
    return {key: value for key, value in values.items() if value is not None}


def optional_str(value: object) -> str | None:
    if value is None:
        return None
    s = str(value).strip()
    return s if s else None


def optional_int(value: object) -> int | None:
    if value is None:
        return None
    return int(value)


def optional_float(value: object) -> float | None:
    if value is None:
        return None
    return float(value)


def last_nonempty_line(text: str) -> str | None:
    if not text:
        return None
    for line in reversed(text.splitlines()):
        stripped = line.strip()
        if stripped:
            return stripped
    return None


def parse_issue_id_arg(raw_issue_id: str) -> int:
    try:
        return int(raw_issue_id)
    except ValueError as exc:
        raise ValueError(f"Invalid issue id: {raw_issue_id}") from exc


def get_issue_heading(content: str) -> re.Match[str] | None:
    return re.search(r"^#\s+Issue\s+#\d+:\s*(.+)$", content, re.MULTILINE) or re.search(
        r"^#\s+(.+)$", content, re.MULTILINE
    )


def has_mojibake(text: str) -> bool:
    return bool(MOJIBAKE_PATTERN.search(text))


def find_encoding_artifacts(
    text: str, *, include_halfwidth_katakana: bool = True
) -> list[tuple[int, str]]:
    patterns = [
        ENCODING_ARTIFACT_PATTERN,
        CP932_DOUBLE_ENCODING_LEAD_CHARACTER_PATTERN,
    ]
    if include_halfwidth_katakana:
        patterns.append(HALFWIDTH_KATAKANA_PATTERN)
    matches = {
        match.start(): match.group()
        for pattern in patterns
        for match in pattern.finditer(text)
    }
    return sorted(matches.items())


def has_encoding_artifacts(text: str, *, include_halfwidth_katakana: bool = True) -> bool:
    return bool(
        find_encoding_artifacts(
            text,
            include_halfwidth_katakana=include_halfwidth_katakana,
        )
    )


def has_non_ascii(text: str) -> bool:
    return bool(NON_ASCII_PATTERN.search(text))


